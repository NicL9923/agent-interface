#!/bin/sh
# Regenerates Sources/WildBotsMacCore/EmbeddedPolicies.swift from the vendored Codex seatbelt
# policies in Sandbox/. EmbeddedPolicyTests fails when the two drift apart.
set -eu
cd "$(dirname "$0")/.."
out=Sources/WildBotsMacCore/EmbeddedPolicies.swift
{
  echo "// Generated by tools/embed-policies.sh from Sandbox/*.sbpl. Do not edit; edit the .sbpl files and rerun."
  echo "// Source: openai/codex (Apache-2.0), see Sandbox/README.md and Sandbox/CODEX-LICENSE."
  echo ""
  echo "enum EmbeddedPolicies {"
  for pair in base:seatbelt_base_policy platformDefaults:seatbelt_read_only_platform_defaults network:seatbelt_network_policy; do
    name=${pair%%:*}
    file=Sandbox/${pair#*:}.sbpl
    if grep -q '"""#' "$file"; then echo "$file contains a raw-string terminator" >&2; exit 1; fi
    echo "  static let $name = #\"\"\""
    cat "$file"
    echo "\"\"\"#"
  done
  echo "}"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
